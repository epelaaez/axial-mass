#!/usr/bin/env python3
"""Generate the one-dimensional (Q^2-only) study XMLs from the production fit XMLs.

The production fit is two-dimensional, log10(Q^2) x p_n. The p_n axis separates
quasi-elastic events (95 % of the selection below p_n = 0.125 GeV) from MEC and
RES (40 to 50 % above 0.3 GeV) inside the fit, so the high-p_n bins constrain
the non-QE normalization while the low-p_n bins measure the axial form factor.
This study removes the p_n axis to show what the slicing buys, and separates
that from what a plain purity cut would buy:

* ``q2_all``    one p_n bin [0, 1]: the production count50 Q^2 bins with every
                selected event integrated over p_n (no p_n information at all);
* ``q2_lowpn``  one p_n bin [0, PN_CUT]: the same Q^2 bins restricted to the
                CCQE-dominated region, without p_n shape (a pure cut; events above
                the cut fall outside the grid and are dropped by PROfit).

Together with the 2D count50 fit and the p_n-range study
(``make_lowpn_study_xmls.py``: 2D slices below the cut, with and without a merged
control bin) these span: no p_n information, purity only, slices only, slices
plus control, full grid. Every variant keeps the production log10(Q^2) edges and
the true-vs-reco Q^2 response binning, and widens the fitted axial splines
exactly as the binning study does (``make_binning_study_xmls.SPLINE_RESTRICT``),
so the natural reference is ``binning_study_fit_results/<family>/count50``.

The grid stays a <bins2D> block with a single p_n bin rather than a 1D <bins>
block, so the same input branches, event selection and out-of-grid behaviour
apply and the study runner needs no special case.

Output: ``xml/oned_study/<family>/<variant>/<fit>.xml`` for the families of the
binning study (nuwro, asimov). Run with ``xml/oned_study/run_all.sh``.

Usage:
    python/scripts/make_oned_study_xmls.py            # write all families and variants
    python/scripts/make_oned_study_xmls.py --check    # also report MC/NuWro occupancy
    python/scripts/make_oned_study_xmls.py --family asimov --fit ma
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_binning_study_xmls as binning  # noqa: E402
import make_lowpn_study_xmls as lowpn  # noqa: E402

ROOT = binning.ROOT
TARGET_DIR = ROOT / "xml" / "oned_study"
FAMILIES = binning.FAMILIES
SCRIPT = "python/scripts/make_oned_study_xmls.py"

PN_CUT = lowpn.PN_CUT   # the same cut as the p_n-range study, so q2_lowpn integrates its lowpn variant

# Production grid: the count50 variant of the binning study.
Q2_EDGES, PN_EDGES, _ = binning.VARIANTS["count50"]
if not any(abs(edge - PN_CUT) < 1e-9 for edge in PN_EDGES):
    raise ValueError(f"PN_CUT={PN_CUT} is not an edge of the count50 p_n grid {PN_EDGES}")

# name -> (log10(Q^2) edges, p_n edges, description)
VARIANTS = {
    "q2_all": (Q2_EDGES, [PN_EDGES[0], PN_EDGES[-1]],
               f"count50 Q^2 bins with p_n integrated over [{PN_EDGES[0]:g}, {PN_EDGES[-1]:g}] (no p_n information)"),
    "q2_lowpn": (Q2_EDGES, [PN_EDGES[0], PN_CUT],
                 f"count50 Q^2 bins with p_n integrated over [{PN_EDGES[0]:g}, {PN_CUT:g}] (purity cut, no p_n shape); "
                 "events above the cut are dropped"),
}


def rebin_xml(text, variant, q2_edges, pn_edges, source_name, family):
    """The production XML with the p_n axis collapsed to one bin and the study's spline box."""
    seen = set()

    def replace(match):
        block = match.group(0)
        unit = re.search(r'unit="([^"]*)"', block)
        unit = unit.group(1) if unit else ""
        if unit == binning.RECO_UNIT:
            seen.add("reco")
            return binning.set_edges(block, q2_edges, pn_edges)
        if unit == binning.RESPONSE_UNIT:
            seen.add("response")
            return binning.set_edges(block, q2_edges, q2_edges)
        raise ValueError(f"unexpected bins2D unit {unit!r} in {source_name}")

    text = binning.BINS2D_RE.sub(replace, text)
    if seen != {"reco", "response"}:
        raise ValueError(f"{source_name}: expected reco and response bins2D blocks, found {sorted(seen)}")
    text, widened = binning.widen_axial_splines(text, source_name)
    nq2, npn = len(q2_edges) - 1, len(pn_edges) - 1
    lo, hi = binning.SPLINE_RESTRICT
    header = (
        f"<!-- Generated by {SCRIPT} from xml/{family}/{source_name}.\n"
        f"     One-dimensional (Q^2-only) study variant '{variant}': {VARIANTS[variant][2]}.\n"
        f"     Reco binning {nq2} log10(Q^2) x {npn} p_n = {nq2 * npn} bins, p_n edges {binning.fmt_edges(pn_edges)};"
        f" {widened} axial spline(s) widened to restrict=\"{lo:g}, {hi:g}\". Do not edit by hand. -->\n"
    )
    declaration = re.match(r"<\?xml[^>]*\?>\s*\n", text)
    if declaration:
        return text[: declaration.end()] + header + text[declaration.end():]
    return header + text


def check_occupancy(variants):
    import numpy as np

    x, y, mc, nuwro = binning.load_reco_arrays()
    print(f"\nRaw event occupancy per reco bin (MC selection: {binning.MC_SELECTION})")
    print(f"{'variant':12s} {'nbins':>5s} {'MC min':>6s} {'MC med':>6s} {'MC<10':>5s} {'NuWro min':>9s} {'MC in range':>11s} {'NuWro in range':>14s}")
    for name in variants:
        q2, pn, _ = VARIANTS[name]
        h_mc = np.histogram2d(x[mc], y[mc], bins=[q2, pn])[0]
        h_nw = np.histogram2d(x[nuwro], y[nuwro], bins=[q2, pn])[0]
        print(f"{name:12s} {h_mc.size:5d} {h_mc.min():6.0f} {np.median(h_mc):6.0f} {(h_mc < 10).sum():5d} "
              f"{h_nw.min():9.0f} {h_mc.sum() / mc.sum():11.0%} {h_nw.sum() / nuwro.sum():14.0%}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--family", action="append", choices=sorted(FAMILIES), help="write only this family (repeatable)")
    parser.add_argument("--variant", action="append", choices=sorted(VARIANTS), help="write only this variant (repeatable)")
    parser.add_argument("--fit", action="append", help="write only this fit stem, e.g. ma (repeatable)")
    parser.add_argument("--check", action="store_true", help="report raw MC/NuWro occupancy per bin for each variant")
    args = parser.parse_args()

    variants = args.variant or list(VARIANTS)
    families = args.family or list(FAMILIES)
    for family in families:
        source_dir = FAMILIES[family]
        sources = sorted(source_dir.glob("*.xml"))
        if args.fit:
            wanted = {Path(fit).stem for fit in args.fit}
            sources = [path for path in sources if path.stem in wanted]
            missing = wanted - {path.stem for path in sources}
            if missing:
                parser.error(f"no such fit in {source_dir}: {', '.join(sorted(missing))}")
        print(f"== {family} (from {source_dir.relative_to(ROOT)})")
        for name in variants:
            q2, pn, _ = VARIANTS[name]
            target = TARGET_DIR / family / name
            target.mkdir(parents=True, exist_ok=True)
            for source in sources:
                (target / source.name).write_text(rebin_xml(source.read_text(), name, q2, pn, source.name, family))
            print(f"   {name:12s} {len(q2) - 1:2d} x {len(pn) - 1:2d} = {(len(q2) - 1) * (len(pn) - 1):3d} bins, "
                  f"p_n edges {binning.fmt_edges(pn)}, {len(sources)} XMLs -> {target.relative_to(ROOT)}")
    if args.check:
        check_occupancy(variants)


if __name__ == "__main__":
    main()

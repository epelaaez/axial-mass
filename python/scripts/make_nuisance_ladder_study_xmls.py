#!/usr/bin/env python3
"""Generate the nuisance-ladder study XMLs from the production fit XMLs.

The production fits float the five interaction-model knobs whose +1 sigma
injection biases F_A(Q^2 = 0.5 GeV^2) by more than 0.2 sigma[F_A]
(python/notebooks/19_modeling_knob_screen.ipynb, Section 8); every other knob is
a covariance term. This study tests the sensitivity of the result to that cut by
floating the next knobs of the injection ranking, cumulatively:

    n5   the production set (RPA_CCQE, XSecShape_CCMEC, MFP_N, DecayAngMEC, FrCEx_N)
    n6   + VecFFCCQEshape     (injection bias on the M_A fit: -0.14)
    n7   + FracPN_CCMEC       (+0.12)
    n8   + xsr_scc_Fv3_SCC    (-0.10)
    n9   + FrAbs_N            (-0.10)
    n10  + NormCCMEC          (-0.04; -0.08 in minerva_k6)

A knob is floated by switching its ``type`` from ``spline_to_covariance`` to
``spline``; two-point model switches are also restricted to [0, 1], as in
production. Nothing else changes, so ``n5`` is the production XML itself and
serves as the in-study reference at the same chain length.

Output: ``xml/nuisance_ladder_study/<family>/<variant>/<fit>.xml`` for the
families asimov, nuwro and opendata. Run with ``xml/nuisance_ladder_study/run_all.sh``.

Usage:
    python/scripts/make_nuisance_ladder_study_xmls.py
    python/scripts/make_nuisance_ladder_study_xmls.py --family asimov --fit ma
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET_DIR = ROOT / "xml" / "nuisance_ladder_study"
FAMILIES = {name: ROOT / "xml" / name for name in ("asimov", "nuwro", "opendata")}
FITS = ("ma", "minerva_k6_nuisance")

# Floated in production; the generator refuses to run if the sources disagree.
BASELINE = ("RPA_CCQE_UBGenie", "XSecShape_CCMEC_UBGenie", "MFP_N_UBGenie",
            "DecayAngMEC_UBGenie", "FrCEx_N_UBGenie")
# Added cumulatively, in the order of the count50 injection ranking
# (tables/injection_study/injection_results_count50.csv, max |bias| over the base fits).
# The flag marks two-point model switches, which get restrict="0, 1".
LADDER = (
    ("VecFFCCQEshape_UBGenie", True),
    ("FracPN_CCMEC_UBGenie", False),
    ("xsr_scc_Fv3_SCC", False),
    ("FrAbs_N_UBGenie", False),
    ("NormCCMEC_UBGenie", False),
)
VARIANTS = {f"n{len(BASELINE) + n}": LADDER[:n] for n in range(len(LADDER) + 1)}

MODELING = re.compile(r"\w+_UBGenie|\w+_SCC")
# The parameters of interest are also type="spline" but are not nuisance knobs.
POI = re.compile(r"MaCCQE_UBGenie|weight_spline_\w+")


def systematic_re(knob):
    return re.compile(r"^(?P<indent>[ \t]*)<systematic (?P<attrs>[^>]*)>" + re.escape(knob) + r"</systematic>",
                      re.MULTILINE)


def floated_knobs(text):
    """Uncommented modeling knobs with type="spline", excluding the parameters of interest."""
    text = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
    found = re.findall(r'<systematic type="spline" [^>]*>([^<]+)</systematic>', text)
    return {name for name in found if MODELING.fullmatch(name) and not POI.fullmatch(name)}


def float_knob(text, knob, two_point, source_name):
    pattern = systematic_re(knob)
    matches = [m for m in pattern.finditer(text)]
    if len(matches) != 1:
        raise ValueError(f"{source_name}: expected one uncommented line for {knob}, found {len(matches)}")
    attrs = matches[0].group("attrs")
    if 'type="spline_to_covariance"' not in attrs:
        raise ValueError(f"{source_name}: {knob} is not a spline_to_covariance term: {attrs}")
    attrs = attrs.replace('type="spline_to_covariance"', 'type="spline"')
    if two_point and "restrict=" not in attrs:
        attrs += ' restrict="0, 1"'
    m = matches[0]
    return text[: m.start()] + f"{m.group('indent')}<systematic {attrs}>{knob}</systematic>" + text[m.end():]


def ladder_xml(text, variant, source_name, family):
    floated = floated_knobs(text)
    if floated != set(BASELINE):
        raise ValueError(f"{source_name}: floated knobs {sorted(floated)} differ from the baseline {sorted(BASELINE)}")
    added = VARIANTS[variant]
    for knob, two_point in added:
        text = float_knob(text, knob, two_point, source_name)
    names = ", ".join(knob for knob, _ in added) or "none (production set)"
    header = (
        f"<!-- Generated by python/scripts/make_nuisance_ladder_study_xmls.py from xml/{family}/{source_name}.\n"
        f"     Nuisance-ladder variant '{variant}': {len(BASELINE) + len(added)} floated modeling knobs;"
        f" added to the production five: {names}. Do not edit by hand. -->\n"
    )
    declaration = re.match(r"<\?xml[^>]*\?>\s*\n", text)
    if declaration:
        return text[: declaration.end()] + header + text[declaration.end():]
    return header + text


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--family", action="append", choices=sorted(FAMILIES), help="write only this family (repeatable)")
    parser.add_argument("--variant", action="append", choices=list(VARIANTS), help="write only this variant (repeatable)")
    parser.add_argument("--fit", action="append", choices=FITS, help="write only this fit (repeatable)")
    args = parser.parse_args()

    for family in args.family or list(FAMILIES):
        print(f"== {family} (from {FAMILIES[family].relative_to(ROOT)})")
        for variant in args.variant or list(VARIANTS):
            target = TARGET_DIR / family / variant
            target.mkdir(parents=True, exist_ok=True)
            for fit in args.fit or FITS:
                source = FAMILIES[family] / f"{fit}.xml"
                (target / source.name).write_text(ladder_xml(source.read_text(), variant, source.name, family))
            added = ", ".join(knob for knob, _ in VARIANTS[variant]) or "production set"
            print(f"   {variant:4s} -> {target.relative_to(ROOT)}  (+ {added})")


if __name__ == "__main__":
    main()

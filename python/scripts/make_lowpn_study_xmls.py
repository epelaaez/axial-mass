#!/usr/bin/env python3
"""Generate the p_n-range (low-p_n) study XMLs from the production fit XMLs.

A reviewer asked whether the fits should use only the low-p_n, CCQE-dominated
events instead of the full p_n range. Below p_n = 0.3 GeV the selected MC is 70
to 95 % quasi-elastic with 2 to 18 % MEC; above it MEC is 40 to 50 %, yet the
remaining QE still makes those bins respond at about half the low-p_n rate to a
change of the axial form factor (python/notebooks/22_pn_range_study.ipynb). This
study fits restricted p_n ranges and compares them with the full count50 grid:

* ``lowpn``       the count50 p_n bins below ``PN_CUT`` only (events above the
                  cut fall outside the grid and are dropped by PROfit);
* ``lowpn_ctrl``  the same plus one merged bin [PN_CUT, 1] as an explicit
                  normalization / MEC control bin without p_n shape;
* ``highpn``      the complement, the count50 bins above the cut, to see how
                  much F_A information the high-p_n region holds on its own.

Every variant keeps the production (count50) log10(Q^2) edges and the true-vs-reco
Q^2 response binning, and widens the fitted axial splines exactly as the binning
study does (``make_binning_study_xmls.SPLINE_RESTRICT``), so the natural
reference is ``binning_study_fit_results/<family>/count50``; the production fits
differ only by that ``restrict`` and by their chain length.

Output: ``xml/lowpn_study/<family>/<variant>/<fit>.xml`` for the families of the
binning study (nuwro, asimov). Run with ``xml/lowpn_study/run_all.sh``.

Usage:
    python/scripts/make_lowpn_study_xmls.py            # write all families and variants
    python/scripts/make_lowpn_study_xmls.py --check    # also report MC/NuWro occupancy
    python/scripts/make_lowpn_study_xmls.py --family asimov --fit ma
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_binning_study_xmls as binning  # noqa: E402

ROOT = binning.ROOT
TARGET_DIR = ROOT / "xml" / "lowpn_study"
FAMILIES = binning.FAMILIES

PN_CUT = 0.30   # GeV; the Fermi momentum, where the MEC fraction crosses from 18 % to 40 %

# Production grid: the count50 variant of the binning study.
Q2_EDGES, PN_EDGES, _ = binning.VARIANTS["count50"]
_low = [edge for edge in PN_EDGES if edge <= PN_CUT + 1e-9]
_high = [edge for edge in PN_EDGES if edge >= PN_CUT - 1e-9]
if abs(_low[-1] - PN_CUT) > 1e-9:
    raise ValueError(f"PN_CUT={PN_CUT} is not an edge of the count50 p_n grid {PN_EDGES}")

# name -> (log10(Q^2) edges, p_n edges, description)
VARIANTS = {
    "lowpn": (Q2_EDGES, _low,
              f"count50 bins with p_n < {PN_CUT:g} GeV only; events above the cut are dropped"),
    "lowpn_ctrl": (Q2_EDGES, _low + [PN_EDGES[-1]],
                   f"count50 bins with p_n < {PN_CUT:g} GeV plus one merged control bin [{PN_CUT:g}, {PN_EDGES[-1]:g}]"),
    "highpn": (Q2_EDGES, _high,
               f"count50 bins with p_n > {PN_CUT:g} GeV only (the complement of lowpn)"),
}


def rebin_xml(text, variant, q2_edges, pn_edges, source_name, family):
    """The production XML with the reco p_n range of ``variant`` and the study's spline box."""
    seen = set()

    def replace(match):
        block = match.group(0)
        unit = re.search(r'unit="([^"]*)"', block)
        unit = unit.group(1) if unit else ""
        if unit == binning.RECO_UNIT:
            seen.add("reco")
            return binning.set_edges(block, q2_edges, pn_edges)
        if unit == binning.RESPONSE_UNIT:
            seen.add("response")
            return binning.set_edges(block, q2_edges, q2_edges)
        raise ValueError(f"unexpected bins2D unit {unit!r} in {source_name}")

    text = binning.BINS2D_RE.sub(replace, text)
    if seen != {"reco", "response"}:
        raise ValueError(f"{source_name}: expected reco and response bins2D blocks, found {sorted(seen)}")
    text, widened = binning.widen_axial_splines(text, source_name)
    nq2, npn = len(q2_edges) - 1, len(pn_edges) - 1
    lo, hi = binning.SPLINE_RESTRICT
    header = (
        f"<!-- Generated by python/scripts/make_lowpn_study_xmls.py from xml/{family}/{source_name}.\n"
        f"     p_n-range study variant '{variant}': {VARIANTS[variant][2]}.\n"
        f"     Reco binning {nq2} log10(Q^2) x {npn} p_n = {nq2 * npn} bins, p_n edges {binning.fmt_edges(pn_edges)};"
        f" {widened} axial spline(s) widened to restrict=\"{lo:g}, {hi:g}\". Do not edit by hand. -->\n"
    )
    declaration = re.match(r"<\?xml[^>]*\?>\s*\n", text)
    if declaration:
        return text[: declaration.end()] + header + text[declaration.end():]
    return header + text


def check_occupancy(variants):
    import numpy as np

    x, y, mc, nuwro = binning.load_reco_arrays()
    print(f"\nRaw event occupancy per reco bin (MC selection: {binning.MC_SELECTION})")
    print(f"{'variant':12s} {'nbins':>5s} {'MC min':>6s} {'MC med':>6s} {'MC<10':>5s} {'NuWro min':>9s} {'MC in range':>11s} {'NuWro in range':>14s}")
    for name in variants:
        q2, pn, _ = VARIANTS[name]
        h_mc = np.histogram2d(x[mc], y[mc], bins=[q2, pn])[0]
        h_nw = np.histogram2d(x[nuwro], y[nuwro], bins=[q2, pn])[0]
        print(f"{name:12s} {h_mc.size:5d} {h_mc.min():6.0f} {np.median(h_mc):6.0f} {(h_mc < 10).sum():5d} "
              f"{h_nw.min():9.0f} {h_mc.sum() / mc.sum():11.0%} {h_nw.sum() / nuwro.sum():14.0%}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--family", action="append", choices=sorted(FAMILIES), help="write only this family (repeatable)")
    parser.add_argument("--variant", action="append", choices=sorted(VARIANTS), help="write only this variant (repeatable)")
    parser.add_argument("--fit", action="append", help="write only this fit stem, e.g. ma (repeatable)")
    parser.add_argument("--check", action="store_true", help="report raw MC/NuWro occupancy per bin for each variant")
    args = parser.parse_args()

    variants = args.variant or list(VARIANTS)
    families = args.family or list(FAMILIES)
    for family in families:
        source_dir = FAMILIES[family]
        sources = sorted(source_dir.glob("*.xml"))
        if args.fit:
            wanted = {Path(fit).stem for fit in args.fit}
            sources = [path for path in sources if path.stem in wanted]
            missing = wanted - {path.stem for path in sources}
            if missing:
                parser.error(f"no such fit in {source_dir}: {', '.join(sorted(missing))}")
        print(f"== {family} (from {source_dir.relative_to(ROOT)})")
        for name in variants:
            q2, pn, _ = VARIANTS[name]
            target = TARGET_DIR / family / name
            target.mkdir(parents=True, exist_ok=True)
            for source in sources:
                (target / source.name).write_text(rebin_xml(source.read_text(), name, q2, pn, source.name, family))
            print(f"   {name:12s} {len(q2) - 1:2d} x {len(pn) - 1:2d} = {(len(q2) - 1) * (len(pn) - 1):3d} bins, "
                  f"p_n edges {binning.fmt_edges(pn)}, {len(sources)} XMLs -> {target.relative_to(ROOT)}")
    if args.check:
        check_occupancy(variants)


if __name__ == "__main__":
    main()
